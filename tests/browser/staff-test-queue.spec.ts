import { test, expect } from '@playwright/test';
import { PrismaClient } from '@prisma/client';
import { randomUUID } from 'node:crypto';
import { createSessionToken } from '../../src/lib/session-token.mjs';
const prisma = new PrismaClient();
let userIds: string[] = [];
test.afterEach(async () => { await prisma.user.deleteMany({ where: { id: { in: userIds } } }); userIds = []; });
test.afterAll(async () => prisma.$disconnect());
test('staff filter the queue and keep filters while changing and refreshing test statuses', async ({ page }) => {
  if (process.env.RUN_DATABASE_TESTS !== '1' || !new URL(process.env.DATABASE_URL!).pathname.endsWith('_test')) throw new Error('Dedicated test database required');
  const suffix = randomUUID().slice(0, 8);
  const session = createSessionToken();
  const staff = await prisma.user.create({ data: { email: `staff-queue-${suffix}@example.test`, role: 'MANAGER', sessions: { create: { tokenHash: session.tokenHash, expiresAt: new Date(Date.now() + 600000) } } } });
  userIds.push(staff.id);
  const customer = await prisma.user.create({ data: { email: `queue-owner-${suffix}@example.test` } });
  userIds.push(customer.id);
  await page.context().addCookies([{ name: 'roma_session', value: session.token, url: 'http://localhost:3200', httpOnly: true, sameSite: 'Lax' }]);
  const prefix = `TEST-QUEUE-${suffix.toUpperCase()}`;
  const rows = Array.from({ length: 27 }, (_, i) => ({ id: `${prefix}-${String(i).padStart(3, '0')}`, userId: customer.id, publicReference: `${prefix}-${String(i).padStart(3, '0')}`, requestKey: randomUUID(), requestHash: '0'.repeat(64), fulfillment: (i % 2 ? 'DELIVERY' : 'PICKUP') as 'DELIVERY' | 'PICKUP', address: i % 2 ? 'Rue fictive 1, 5000 Namur' : null, zoneId: i % 2 ? 'namur-centre' : null, contactName: 'File navigateur', phone: '081 00 00 00', status: (i === 26 ? 'COMPLETED' : i === 25 ? 'READY' : 'PENDING') as 'COMPLETED' | 'READY' | 'PENDING', totalCents: 1200, itemsSnapshot: [{ productId: 'queue-fixture-product', label: 'Pizza test de file', quantity: 1, extraIds: [], extraLabels: [], removedIngredients: [], unitCents: 1200, totalCents: 1200 }], placedAt: new Date('2026-01-01T12:00:00Z') }));
  await prisma.testOrder.createMany({ data: rows });
  await page.goto(`/gerant/commandes-test?q=${prefix}`);
  const queue = page.getByRole('region', { name: 'File des essais', exact: true });
  await expect(queue.getByRole('article')).toHaveCount(20);
  await expect(queue.getByRole('status')).toContainText('Page 1 sur 2');
  await expect(queue.getByRole('article').first()).toHaveAccessibleName(rows[0].publicReference);
  await queue.getByRole('link', { name: 'Page suivante', exact: true }).click();
  await expect(queue.getByRole('article')).toHaveCount(6);
  await expect(queue.getByRole('status')).toContainText('Page 2 sur 2');
  await expect(queue.getByLabel('Référence à rechercher', { exact: true })).toHaveValue(prefix);
  await queue.getByLabel('Statut des essais', { exact: true }).selectOption('PENDING');
  await queue.getByLabel('Mode des essais', { exact: true }).selectOption('DELIVERY');
  await queue.getByRole('button', { name: 'Appliquer les filtres', exact: true }).click();
  await expect(queue.getByRole('article')).toHaveCount(12);
  await expect(queue.getByRole('status')).toContainText('Page 1 sur 1');
  const accepted = queue.getByRole('article', { name: rows[1].publicReference, exact: true });
  await accepted.getByRole('button', { name: 'Test accepté', exact: true }).click();
  await expect(accepted).toHaveCount(0);
  await expect(queue.getByRole('article')).toHaveCount(11);
  expect((await prisma.testOrder.findUniqueOrThrow({ where: { id: rows[1].id } })).status).toBe('ACCEPTED');
  await expect(queue.getByLabel('Statut des essais', { exact: true })).toHaveValue('PENDING');
  await expect(queue.getByLabel('Mode des essais', { exact: true })).toHaveValue('DELIVERY');
  // Simulate a change in another staff session, then refresh the filtered list.
  await prisma.testOrder.update({ where: { id: rows[3].id }, data: { status: 'CANCELLED', revision: { increment: 1 } } });
  const stale = queue.getByRole('article', { name: rows[3].publicReference, exact: true });
  await stale.getByRole('button', { name: 'Test accepté', exact: true }).click();
  await expect(stale.getByRole('alert')).toContainText('Le statut a changé');
  await queue.getByRole('button', { name: 'Actualiser la liste', exact: true }).click();
  await expect(stale).toHaveCount(0);
  await expect(queue.getByRole('article')).toHaveCount(10);
  await queue.getByLabel('Référence à rechercher', { exact: true }).fill(rows[1].publicReference.toLowerCase());
  await queue.getByRole('button', { name: 'Appliquer les filtres', exact: true }).click();
  await expect(queue.getByText('Aucun essai ne correspond à ces filtres.')).toBeVisible();
  await queue.getByLabel('Statut des essais', { exact: true }).selectOption('all');
  await queue.getByRole('button', { name: 'Appliquer les filtres', exact: true }).click();
  await expect(queue.getByRole('article')).toHaveCount(1);
  await expect(queue.getByRole('article')).toContainText('Test accepté');
  await queue.getByLabel('Référence à rechercher', { exact: true }).fill(prefix);
  await queue.getByLabel('Mode des essais', { exact: true }).selectOption('');
  await queue.getByLabel('Ordre des essais', { exact: true }).selectOption('newest');
  await queue.getByRole('button', { name: 'Appliquer les filtres', exact: true }).click();
  await expect(queue.getByRole('article').first()).toHaveAccessibleName(rows[26].publicReference);
  await queue.getByRole('link', { name: 'Réinitialiser la file', exact: true }).click();
  await expect(queue.getByLabel('Référence à rechercher', { exact: true })).toHaveValue('');
  await expect(queue.getByLabel('Statut des essais', { exact: true })).toHaveValue('active');
  await expect(queue.getByLabel('Mode des essais', { exact: true })).toHaveValue('');
  await expect(queue.getByLabel('Ordre des essais', { exact: true })).toHaveValue('oldest');
});
