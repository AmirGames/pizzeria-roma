import { test, expect } from '@playwright/test';
import { PrismaClient } from '@prisma/client';
import { randomUUID } from 'node:crypto';
const prisma = new PrismaClient();
let email: string;
test.afterEach(async () => { if (email) await prisma.user.deleteMany({ where: { email } }); });
test.afterAll(async () => prisma.$disconnect());
test('a customer searches and paginates an owned history larger than fifty orders', async ({ page }) => {
  if (process.env.RUN_DATABASE_TESTS !== '1' || !new URL(process.env.DATABASE_URL!).pathname.endsWith('_test')) throw new Error('Dedicated test database required');
  const suffix = randomUUID();
  email = `history-browser-${suffix}@example.test`;
  const registration = await page.request.post('http://localhost:3200/api/customer/auth', { headers: { origin: 'http://localhost:3200' }, data: { action: 'register', name: 'Historique navigateur', email, password: 'Browser-history-password' } });
  expect(registration.status()).toBe(200);
  const user = await prisma.user.findUniqueOrThrow({ where: { email } });
  const rows = Array.from({ length: 55 }, (_, i) => ({ id: `history-browser-${suffix}-${String(i).padStart(3, '0')}`, userId: user.id, publicReference: `TEST-${suffix.toUpperCase()}-${String(i).padStart(3, '0')}`, requestKey: randomUUID(), requestHash: '0'.repeat(64), fulfillment: 'PICKUP' as const, contactName: 'Historique navigateur', phone: '081 00 00 00', status: (i % 2 ? 'CANCELLED' : 'PENDING') as 'CANCELLED' | 'PENDING', totalCents: 1200, itemsSnapshot: [{ productId: 'history-fixture-product', label: 'Pizza historique', quantity: 1, extraIds: [], extraLabels: [], removedIngredients: [], unitCents: 1200, totalCents: 1200 }], placedAt: new Date('2026-02-01T12:00:00Z') }));
  await prisma.testOrder.createMany({ data: rows });
  await page.goto('/compte');
  const history = page.getByRole('region', { name: 'Mes commandes de test', exact: true });
  await expect(history.getByRole('listitem')).toHaveCount(20);
  await expect(history.getByRole('status')).toContainText('Page 1 sur 3');
  await expect(history.getByRole('link', { name: rows[0].publicReference, exact: true })).toHaveCount(0);
  await history.getByRole('link', { name: 'Page suivante', exact: true }).click();
  await expect(history.getByRole('status')).toContainText('Page 2 sur 3');
  await history.getByRole('link', { name: 'Page suivante', exact: true }).click();
  await expect(history.getByRole('status')).toContainText('Page 3 sur 3');
  await expect(history.getByRole('listitem')).toHaveCount(15);
  await history.getByRole('link', { name: rows[0].publicReference, exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Commande de test enregistrée', exact: true })).toBeVisible();
  await expect(page.getByText(rows[0].publicReference, { exact: true })).toBeVisible();
  await page.goBack();
  await expect(history.getByRole('status')).toContainText('Page 3 sur 3');
  await history.getByLabel('Statut de l’essai', { exact: true }).selectOption('CANCELLED');
  await history.getByRole('button', { name: 'Rechercher mes essais', exact: true }).click();
  await expect(history.getByRole('status')).toContainText('Page 1 sur 2');
  await expect(history.getByRole('status')).toContainText('sur 27');
  await history.getByRole('link', { name: 'Page suivante', exact: true }).click();
  await expect(history.getByRole('status')).toContainText('Page 2 sur 2');
  await expect(history.getByLabel('Statut de l’essai', { exact: true })).toHaveValue('CANCELLED');
  await expect(history.getByRole('listitem')).toHaveCount(7);
  await history.getByLabel('Référence de l’essai', { exact: true }).fill(rows[0].publicReference.toLowerCase());
  await history.getByRole('button', { name: 'Rechercher mes essais', exact: true }).click();
  await expect(history.getByText('Aucun essai ne correspond à ces filtres.')).toBeVisible();
  await history.getByLabel('Statut de l’essai', { exact: true }).selectOption('');
  await history.getByRole('button', { name: 'Rechercher mes essais', exact: true }).click();
  await expect(history.getByRole('listitem')).toHaveCount(1);
  await expect(history.getByRole('link', { name: rows[0].publicReference, exact: true })).toBeVisible();
  await history.getByRole('link', { name: 'Réinitialiser les filtres', exact: true }).click();
  await expect(history.getByRole('listitem')).toHaveCount(20);
  await expect(history.getByLabel('Référence de l’essai', { exact: true })).toHaveValue('');
  await expect(history.getByLabel('Statut de l’essai', { exact: true })).toHaveValue('');
  expect(await prisma.testOrder.count({ where: { userId: user.id } })).toBe(55);
});
