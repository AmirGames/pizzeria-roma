import { test, expect } from '@playwright/test';
import { PrismaClient } from '@prisma/client';
import { randomUUID } from 'node:crypto';
const prisma = new PrismaClient();
let email: string;
let categoryId: string;
test.afterEach(async () => {
  if (email) await prisma.user.deleteMany({ where: { email } });
  if (categoryId) { await prisma.product.deleteMany({ where: { categoryId } }); await prisma.menuCategory.deleteMany({ where: { id: categoryId } }); }
});
test.afterAll(async () => prisma.$disconnect());
test('a customer confirms a repeat selection at current prices while preserving their cart', async ({ page }) => {
  if (process.env.RUN_DATABASE_TESTS !== '1' || !new URL(process.env.DATABASE_URL!).pathname.endsWith('_test')) throw new Error('Dedicated test database required');
  const category = await prisma.menuCategory.create({ data: { nameFr: 'Reprise navigateur', nameEn: 'Reorder browser', fulfillmentCategory: 'PIZZA' } });
  categoryId = category.id;
  const product = await prisma.product.create({ data: { categoryId, nameFr: 'Pizza historique', nameEn: 'History pizza', baseCents: 0, removableIngredients: ['Tomate'], sizes: { create: { label: '33 cm', priceCents: 1200 } }, extras: { create: { nameFr: 'Chèvre', nameEn: 'Cheese', priceCents: 150 } } }, include: { sizes: true, extras: true } });
  const otherProduct = await prisma.product.create({ data: { categoryId, nameFr: 'Pizza déjà au panier', nameEn: 'Existing pizza', baseCents: 0, sizes: { create: { label: '33 cm', priceCents: 500 } } }, include: { sizes: true } });
  email = `reorder-browser-${randomUUID()}@example.test`;
  const headers = { origin: 'http://localhost:3200' };
  expect((await page.request.post('http://localhost:3200/api/customer/auth', { headers, data: { action: 'register', name: 'Reprise navigateur', email, password: 'Browser-reorder-password' } })).status()).toBe(200);
  expect((await page.request.post('http://localhost:3200/api/customer/addresses', { headers, data: { label: 'Domicile test', address: 'Rue fictive 8, 5000 Namur', zoneId: 'namur-centre', isDefault: true } })).status()).toBe(201);
  const selection = { productId: product.id, sizeId: product.sizes[0].id, extraIds: [product.extras[0].id], removedIngredients: ['Tomate'], quantity: 2 };
  const creation = await page.request.post('http://localhost:3200/api/test-orders', { headers, data: { items: [selection], mode: 'pickup', contactName: 'Reprise navigateur', phone: '081 00 00 00', comment: 'Ancien commentaire', requestKey: randomUUID(), expectedTotalCents: 2700 } });
  expect(creation.status()).toBe(201);
  const { id } = await creation.json() as { id: string };
  await prisma.productSize.update({ where: { id: product.sizes[0].id }, data: { priceCents: 1400 } });
  await page.goto(`/compte/commandes/${id}`);
  const existing = [{ productId: otherProduct.id, sizeId: otherProduct.sizes[0].id, extraIds: [], quantity: 1 }, { ...selection, quantity: 1 }];
  await page.evaluate(existing => localStorage.setItem('pizzeria-roma-catalog-cart-v1', JSON.stringify(existing)), existing);
  const reorder = page.getByRole('region', { name: 'Commander à nouveau', exact: true });
  await reorder.getByRole('button', { name: 'Commander à nouveau', exact: true }).click();
  await expect(reorder.getByText('Le total a changé :', { exact: false })).toContainText('31,00');
  await expect(reorder.getByText('Supplément Chèvre · Sans Tomate', { exact: false })).toBeVisible();
  await reorder.getByRole('button', { name: 'Annuler la reprise', exact: true }).click();
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('pizzeria-roma-catalog-cart-v1')!))).toEqual(existing);
  await reorder.getByRole('button', { name: 'Commander à nouveau', exact: true }).click();
  await expect(reorder.getByRole('heading', { name: 'Articles aux prix actuels' })).toBeVisible();
  // A cart change after preparation must survive confirmation too.
  await page.evaluate(() => {
    const cart = JSON.parse(localStorage.getItem('pizzeria-roma-catalog-cart-v1')!);
    cart[0].quantity = 4; localStorage.setItem('pizzeria-roma-catalog-cart-v1', JSON.stringify(cart));
  });
  await reorder.getByRole('button', { name: 'Ajouter ces articles au panier', exact: true }).click();
  await expect(reorder.getByText('Les articles ont été ajoutés au panier.', { exact: false })).toBeVisible();
  const cart = await page.evaluate(() => JSON.parse(localStorage.getItem('pizzeria-roma-catalog-cart-v1')!) as Array<{ productId: string; quantity: number; extraIds: string[]; removedIngredients?: string[] }>);
  expect(cart[0].quantity).toBe(4); expect(cart[1].quantity).toBe(3);
  expect(cart[1].extraIds).toEqual(selection.extraIds); expect(cart[1].removedIngredients).toEqual(['Tomate']);
  expect(await prisma.testOrder.count({ where: { user: { email } } })).toBe(1);
  const original = await prisma.testOrder.findUniqueOrThrow({ where: { id } });
  expect(original.totalCents).toBe(2700); expect(original.comment).toBe('Ancien commentaire');
  await reorder.getByRole('link', { name: 'Voir mon panier', exact: true }).click();
  await expect(page.getByRole('complementary', { name: 'Récapitulatif du panier' })).toContainText('66,50');
  await page.getByRole('link', { name: 'Commander en mode test', exact: true }).click();
  await page.getByLabel('Mode', { exact: true }).selectOption('delivery');
  await expect(page.getByLabel('Adresse fictive', { exact: true })).toHaveValue('Rue fictive 8, 5000 Namur');
  await page.getByLabel('Téléphone fictif').fill('081 00 00 00');
  await expect(page.getByText('Total du test :')).toContainText('66,50');
  await page.getByRole('button', { name: 'Confirmer la commande de test', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Commande de test enregistrée', exact: true })).toBeVisible();
  const repeated = await prisma.testOrder.findFirstOrThrow({ where: { user: { email }, id: { not: id } } });
  expect(repeated.totalCents).toBe(6650);
  expect(repeated.address).toBe('Rue fictive 8, 5000 Namur');
  expect(repeated.comment).toBe('');
  expect((await prisma.testOrder.findUniqueOrThrow({ where: { id } })).totalCents).toBe(2700);
  expect(await prisma.testOrder.count({ where: { user: { email } } })).toBe(2);
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem('pizzeria-roma-catalog-cart-v1')!))).toEqual([]);
  await page.goto(`/compte/commandes/${id}`);
  await prisma.productExtra.update({ where: { id: product.extras[0].id }, data: { active: false } });
  await reorder.getByRole('button', { name: 'Commander à nouveau', exact: true }).click();
  await expect(reorder.getByRole('alert')).toContainText('n’est plus disponible');
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('pizzeria-roma-catalog-cart-v1')!))).toEqual([]);
});
