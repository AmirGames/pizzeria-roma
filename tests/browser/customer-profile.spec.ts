import { test, expect } from '@playwright/test';
import { PrismaClient } from '@prisma/client';
import { randomUUID } from 'node:crypto';
const prisma = new PrismaClient();
let email: string;
test.afterEach(async () => { if (email) await prisma.user.deleteMany({ where: { email } }); });
test.afterAll(async () => prisma.$disconnect());
test('a customer updates their profile and changes password while other sessions are revoked', async ({ page, browser }) => {
  if (process.env.RUN_DATABASE_TESTS !== '1' || !new URL(process.env.DATABASE_URL!).pathname.endsWith('_test')) throw new Error('Dedicated test database required');
  email = `profile-${randomUUID()}@example.test`;
  const password = 'Browser-profile-password';
  const newPassword = 'Browser-new-profile-password';
  await page.goto('/compte');
  await page.getByRole('button', { name: 'Créer un compte', exact: true }).click();
  await page.getByLabel('Votre nom').fill('Profil initial');
  await page.getByLabel('Adresse e-mail').fill(email);
  await page.getByLabel('Mot de passe').fill(password);
  await page.getByRole('button', { name: 'Créer mon compte de test' }).click();
  await expect(page.getByRole('heading', { name: 'Bonjour Profil initial' })).toBeVisible();
  await page.getByText('Mes coordonnées et mon mot de passe', { exact: true }).click();
  await page.getByLabel('Nom du profil').fill('Profil modifié');
  await page.getByLabel('Téléphone du profil').fill('081 22 22 22');
  await page.getByRole('button', { name: 'Enregistrer mes coordonnées' }).click();
  await expect(page.getByRole('heading', { name: 'Bonjour Profil modifié' })).toBeVisible();
  const second = await browser.newContext();
  try {
    const login = await second.request.post('http://localhost:3200/api/customer/auth', { headers: { origin: 'http://localhost:3200' }, data: { action: 'login', email, password } });
    expect(login.status()).toBe(200);
    expect((await second.request.get('http://localhost:3200/api/test-orders/unknown')).status()).toBe(404);
    await page.getByLabel('Mot de passe actuel', { exact: true }).fill(password);
    await page.getByLabel('Nouveau mot de passe', { exact: true }).fill(newPassword);
    await page.getByLabel('Confirmer le nouveau mot de passe', { exact: true }).fill('Mismatch-test-password');
    await page.getByRole('button', { name: 'Changer mon mot de passe', exact: true }).click();
    await expect(page.getByText('Les nouveaux mots de passe ne correspondent pas.')).toBeVisible();
    await page.getByLabel('Confirmer le nouveau mot de passe', { exact: true }).fill(newPassword);
    await page.getByRole('button', { name: 'Changer mon mot de passe', exact: true }).click();
    await expect(page.getByText('Mot de passe changé. Les autres sessions ont été déconnectées.')).toBeVisible();
    expect((await second.request.get('http://localhost:3200/api/test-orders/unknown')).status()).toBe(401);
    await page.reload();
    await expect(page.getByRole('heading', { name: 'Bonjour Profil modifié' })).toBeVisible();
    await page.getByText('Mes coordonnées et mon mot de passe', { exact: true }).click();
    await expect(page.getByLabel('Téléphone du profil')).toHaveValue('081 22 22 22');
    await page.getByRole('button', { name: 'Se déconnecter' }).click();
    await page.getByLabel('Adresse e-mail').fill(email);
    await page.getByLabel('Mot de passe').fill(password);
    await page.getByRole('button', { name: 'Ouvrir mon espace' }).click();
    await expect(page.getByText('Connexion ou inscription impossible.', { exact: false })).toBeVisible();
    await page.getByLabel('Mot de passe').fill(newPassword);
    await page.getByRole('button', { name: 'Ouvrir mon espace' }).click();
    await expect(page.getByRole('heading', { name: 'Bonjour Profil modifié' })).toBeVisible();
  } finally { await second.close(); }
});
