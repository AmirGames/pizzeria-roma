import { test, expect } from '@playwright/test';
import { PrismaClient } from '@prisma/client';
import { randomUUID } from 'node:crypto';
import { selectTestSlot } from './support/select-test-slot';
const prisma = new PrismaClient();
let email: string;
let categoryId: string;
test.afterEach(async () => {
  if (email) await prisma.user.deleteMany({ where: { email } });
  if (categoryId) { await prisma.product.deleteMany({ where: { categoryId } }); await prisma.menuCategory.deleteMany({ where: { id: categoryId } }); }
});
test.afterAll(async () => prisma.$disconnect());
test('a customer manages private addresses and uses a saved address for a delivery test', async ({ page }) => {
  if (process.env.RUN_DATABASE_TESTS !== '1' || !new URL(process.env.DATABASE_URL!).pathname.endsWith('_test')) throw new Error('Dedicated test database required');
  const category = await prisma.menuCategory.create({ data: { nameFr: 'Adresses navigateur', nameEn: 'Addresses browser', fulfillmentCategory: 'PIZZA' } });
  categoryId = category.id;
  const product = await prisma.product.create({ data: { categoryId, nameFr: 'Pizza carnet', nameEn: 'Address pizza', baseCents: 0, sizes: { create: { label: '33 cm', priceCents: 1200 } } }, include: { sizes: true } });
  const cart = [{ productId: product.id, sizeId: product.sizes[0].id, extraIds: [], removedIngredients: [], quantity: 2 }];
  await page.addInitScript(cart => { if (!sessionStorage.getItem('address-cart-seeded')) { localStorage.setItem('pizzeria-roma-catalog-cart-v1', JSON.stringify(cart)); sessionStorage.setItem('address-cart-seeded', '1'); } }, cart);
  email = `address-browser-${randomUUID()}@example.test`;
  const registration = await page.request.post('http://localhost:3200/api/customer/auth', { headers: { origin: 'http://localhost:3200' }, data: { action: 'register', name: 'Carnet navigateur', email, password: 'Browser-address-password' } });
  expect(registration.status()).toBe(200);
  await page.goto('/compte');
  const book = page.getByRole('region', { name: 'Mes adresses', exact: true });
  await expect(book.getByText('Aucune adresse enregistrée.')).toBeVisible();
  await book.getByLabel('Nom de l’adresse', { exact: true }).fill('Domicile');
  await book.getByLabel('Adresse enregistrée fictive').fill('Rue fictive 1, 5000 Namur');
  await book.getByLabel('Zone de l’adresse').selectOption('belgrade');
  await book.getByRole('button', { name: 'Ajouter l’adresse', exact: true }).click();
  await expect(book.getByRole('listitem')).toHaveCount(1);
  await book.getByLabel('Nom de l’adresse', { exact: true }).fill('Travail');
  await book.getByLabel('Adresse enregistrée fictive').fill('Rue fictive 2, 5000 Namur');
  await book.getByRole('button', { name: 'Ajouter l’adresse', exact: true }).click();
  await expect(book.getByRole('listitem')).toHaveCount(2);
  await book.getByRole('button', { name: 'Définir Travail par défaut', exact: true }).click();
  await expect(book.getByRole('listitem').filter({ hasText: 'Travail' })).toContainText('Par défaut');
  await book.getByRole('button', { name: 'Modifier Domicile', exact: true }).click();
  await book.getByLabel('Adresse enregistrée fictive').fill('Rue fictive 3, 5000 Namur');
  await book.getByRole('button', { name: 'Enregistrer l’adresse', exact: true }).click();
  await expect(book.getByRole('listitem').filter({ hasText: 'Domicile' })).toContainText('Rue fictive 3');
  await page.reload();
  await expect(book.getByRole('listitem')).toHaveCount(2);
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('pizzeria-roma-catalog-cart-v1')!))).toEqual(cart);
  await page.getByRole('link', { name: 'Passer une commande de test' }).click();
  await expect(page).toHaveURL(/\/commande\/test$/);
  await expect(page.getByRole('heading', { name: 'Livraison ou à emporter', exact: true })).toBeVisible();
  await expect(page.getByLabel('Mode', { exact: true })).toBeVisible();
  await page.getByLabel('Mode', { exact: true }).selectOption('delivery');
  await expect(page.getByLabel('Adresse fictive', { exact: true })).toHaveValue('Rue fictive 2, 5000 Namur');
  await page.getByLabel('Adresse de livraison', { exact: true }).selectOption({ label: 'Domicile' });
  await expect(page.getByLabel('Adresse fictive', { exact: true })).toHaveValue('Rue fictive 3, 5000 Namur');
  await page.getByLabel('Adresse fictive', { exact: true }).fill('Rue ponctuelle 9, 5000 Namur');
  await expect(page.getByLabel('Adresse de livraison', { exact: true })).toHaveValue('');
  await page.getByLabel('Mode', { exact: true }).selectOption('pickup');
  await page.getByLabel('Téléphone fictif').fill('081 00 00 00');
  await selectTestSlot(page, 2);
  await page.getByRole('button', { name: 'Confirmer la commande de test' }).click();
  await expect(page.getByRole('heading', { name: 'Commande de test enregistrée' })).toBeVisible();
  const order = await prisma.testOrder.findFirstOrThrow({ where: { user: { email } } });
  expect(order.address).toBeNull();
  expect(order.zoneId).toBeNull();
  expect(order.totalCents).toBe(2400);
  await page.getByRole('link', { name: 'Mon espace client', exact: true }).click();
  await expect(book.getByRole('listitem').filter({ hasText: 'Domicile' })).toContainText('Rue fictive 3');
  await book.getByRole('button', { name: 'Supprimer Travail', exact: true }).click();
  await book.getByRole('button', { name: 'Confirmer la suppression', exact: true }).click();
  await expect(book.getByRole('listitem')).toHaveCount(1);
  await expect(book.getByRole('listitem')).toContainText('Par défaut');
  await book.getByRole('button', { name: 'Supprimer Domicile', exact: true }).click();
  await book.getByRole('button', { name: 'Confirmer la suppression', exact: true }).click();
  await expect(book.getByText('Aucune adresse enregistrée.')).toBeVisible();
  expect((await prisma.testOrder.findUniqueOrThrow({ where: { id: order.id } })).address).toBe(order.address);
});
